// assign variables
let number1: number = 56.9
let number2: number = 89.7
let number3: number = 90.2

// INPUT - none

// PROCESS
// calculate average
let average: number = (number1 + number2 + number3) / 3

// OUTPUT
console.log("The average of " + number1 + ", " + number2 + ", and " + number3 + ", is " + average)

